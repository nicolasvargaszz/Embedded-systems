#!/usr/bin/env python3
"""Install an Edge Impulse Arduino export (ZIP) into the isolated .arduino/ for the Wio build.

Replaces any previously installed *_inferencing model, removes the espressif porting folder
(it breaks SAMD builds with "Conflicting CPU architectures") and writes firmware/WioCoach/ei_model.h.
Then build with: python3 tools/build.py wio --ei --upload PORT
"""
import argparse
import shutil
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIBS = ROOT / ".arduino" / "user" / "libraries"
MODEL_HEADER = ROOT / "firmware" / "WioCoach" / "ei_model.h"

if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("zip", type=Path, help="ZIP from Edge Impulse > Deployment > Arduino library")
    a = p.parse_args()
    if not (ROOT / ".arduino" / "config.yaml").is_file():
        p.error("Run tools/install_arduino.py first")
    with zipfile.ZipFile(a.zip) as z:
        names = z.namelist()
        if any(Path(n).is_absolute() or ".." in Path(n).parts for n in names):
            p.error("Unsafe archive path")
        headers = [Path(n) for n in names
                   if len(Path(n).parts) == 3 and Path(n).parts[1] == "src" and n.endswith("_inferencing.h")]
        if len(headers) != 1:
            p.error("Not an Edge Impulse Arduino library export (no single src/*_inferencing.h)")
        library, header = headers[0].parts[0], headers[0].name
        LIBS.mkdir(parents=True, exist_ok=True)
        for old in LIBS.glob("*_inferencing"):
            shutil.rmtree(old)
        z.extractall(LIBS)
    espressif = LIBS / library / "src" / "edge-impulse-sdk" / "porting" / "espressif"
    if espressif.is_dir():
        shutil.rmtree(espressif)
    MODEL_HEADER.write_text(f"#pragma once\n// Generated by tools/install_ei.py; not in git.\n#include <{header}>\n")
    print(f"Installed {library} ({header}). Next: python3 tools/build.py wio --ei --upload PORT")
